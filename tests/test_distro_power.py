def hold_env(env, tmp_path, dev, extra=None):
    e = {"PATH": os.environ["PATH"], "ETC_ROOT": str(env["etc"]), "SYSFS_ROOT": str(env["sysfs"]),
         "TAOS_POWER_BIN": str(CLI), "TAOS_POWER_DMA_LATENCY": str(dev),
         "TAOS_POWER_RUNDIR": str(env["run"])}
    e.update(extra or {})
    return e


@pytest.mark.parametrize("shell", SHELLS)
def test_holder_exits_zero_without_opening_device_when_nothing_to_hold(env, tmp_path, shell):
    dev = tmp_path / "dma"
    for body in ("PROFILE=always-on\nTUNE=off\n",                        # default: tune off
                 "PROFILE=always-on\nTUNE=performance\nLATENCY_US=0\n",  # hold disabled
                 "PROFILE=battery\nTUNE=performance\n"):                 # battery profile
        w(conf(env), body)
        res = subprocess.run([shell, str(HOLD)], env=hold_env(env, tmp_path, dev),
                             capture_output=True, text=True, timeout=10)
        assert res.returncode == 0, res.stderr
        assert not dev.exists()  # the device was never opened (opening would create it)


@pytest.mark.parametrize("shell", SHELLS)
@pytest.mark.parametrize("value,expected", [(100, b"\x64\x00\x00\x00"), (70000, b"\x70\x11\x01\x00")])
def test_holder_holds_request_and_exits_zero_on_sigterm(env, tmp_path, shell, value, expected):
    dev = tmp_path / "dma"
    dev.write_bytes(b"")
    w(conf(env), f"PROFILE=always-on\nTUNE=performance\nLATENCY_US={value}\n")
    p = subprocess.Popen([shell, str(HOLD)], env=hold_env(env, tmp_path, dev),
                         stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    try:
        time.sleep(0.3)
        assert p.poll() is None, "holder must keep running"
        assert dev.read_bytes() == expected
        st = json.loads(run(env, "status", "--json").stdout)
        assert st["holder_running"] is True and st["latency_request_us"] == value
        p.send_signal(signal.SIGTERM)
        assert p.wait(timeout=5) == 0
    finally:
        if p.poll() is None:
            p.kill()
    assert not (env["run"] / "latency-hold.pid").exists()
    assert json.loads(run(env, "status", "--json").stdout)["holder_running"] is False


def test_holder_does_not_leave_sleeper_holding_fd(env, tmp_path):
    dev = tmp_path / "dma"
    dev.write_bytes(b"")
    w(conf(env), "PROFILE=always-on\nTUNE=performance\n")
    p = subprocess.Popen(["sh", str(HOLD)], env=hold_env(env, tmp_path, dev))
    time.sleep(0.3)
    kids = subprocess.run(["pgrep", "-P", str(p.pid)], capture_output=True, text=True).stdout.split()
    assert kids
    for k in kids:
        assert not (Path("/proc") / k / "fd" / "3").exists()
    p.terminate()
    p.wait(timeout=5)
    time.sleep(0.1)
    for k in kids:
        assert not Path("/proc", k).exists()


