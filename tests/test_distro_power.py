def tune_fixture(env):
    s = env["sysfs"]
    add_cpu(s, 0, epp="balance_performance")                       # has EPP, offers performance
    add_cpu(s, 1, epp="balance_performance", avail="power balance_power")  # EPP without performance
    add_cpu(s, 2)                                                  # no EPP: governor fallback
    add_cpu(s, 3, govs="powersave")                                # no EPP, no performance governor
    return s


def cpu_file(env, n, name):
    return env["sysfs"] / f"devices/system/cpu/cpu{n}/cpufreq/{name}"


