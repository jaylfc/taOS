@pytest.mark.parametrize("shell", SHELLS)
def test_apply_always_on_writes_exact_dropins_and_touches_no_cpu(env, shell):
    add_cpu(env["sysfs"], 0, epp="balance_performance")
    add_cpu(env["sysfs"], 1)
    cpu_before = snapshot(env["sysfs"])
    res = run(env, "apply", shell=shell)
    assert res.returncode == 0, res.stderr
    assert drop_logind(env).read_text() == LOGIND
    assert drop_sleep(env).read_text() == SLEEP
    assert snapshot(env["sysfs"]) == cpu_before
    assert not env["run"].exists()  # no marker, no holder
    assert run(env, "hold-value").stdout == ""


def test_apply_battery_removes_dropins_and_changes_nothing_else(env):
    w(drop_logind(env), LOGIND)
    w(drop_sleep(env), SLEEP)
    w(env["etc"] / "systemd/logind.conf.d/10-other.conf", "[Login]\n")
    w(conf(env), "PROFILE=battery\nTUNE=performance\n")
    add_cpu(env["sysfs"], 0, epp="balance_performance")
    cpu_before = snapshot(env["sysfs"])
    assert run(env, "apply").returncode == 0
    assert not drop_logind(env).exists() and not drop_sleep(env).exists()
    assert (env["etc"] / "systemd/logind.conf.d/10-other.conf").exists()
    assert snapshot(env["sysfs"]) == cpu_before  # tune is inactive on battery
    assert run(env, "hold-value").stdout == ""
    assert "inactive" in run(env, "status").stdout


def test_apply_is_idempotent(env):
    run(env, "apply")
    snap, mt = snapshot(env["etc"]), mtimes(env["etc"])
    time.sleep(0.02)
    assert run(env, "apply").returncode == 0
    assert snapshot(env["etc"]) == snap
    assert mtimes(env["etc"]) == mt


def test_dry_run_writes_nothing(env):
    res = run(env, "apply", "--dry-run", extra={"TAOS_POWER_NO_APPLY": "0"})
    assert res.returncode == 0
    assert "+ write" in res.stdout and "systemctl kill -s HUP systemd-logind" in res.stdout
    assert "restart taos-power.service" in res.stdout
    assert not drop_logind(env).exists()


def test_apply_runs_systemctl_through_stub(env, tmp_path):
    bindir = tmp_path / "bin"
    log = tmp_path / "calls.log"
    w(bindir / "systemctl", f'#!/bin/sh\necho "$@" >> {log}\n')
    (bindir / "systemctl").chmod(0o755)
    sd = tmp_path / "sd"
    sd.mkdir()
    extra = {"TAOS_POWER_NO_APPLY": "0", "TAOS_POWER_SYSTEMD_DIR": str(sd)}
    path = f"{bindir}:{os.environ['PATH']}"
    assert run(env, "apply", extra=extra, path=path).returncode == 0
    assert log.read_text().splitlines() == ["kill -s HUP systemd-logind",
                                            "restart taos-power.service"]
    log.unlink()
    run(env, "apply", extra=extra, path=path)  # unchanged: no HUP, still restarts
    assert log.read_text().splitlines() == ["restart taos-power.service"]
    log.unlink()
    # no systemd running (chroot): nothing is called
    extra["TAOS_POWER_SYSTEMD_DIR"] = str(tmp_path / "missing")
    assert run(env, "apply", extra=extra, path=path).returncode == 0
    assert not log.exists()


