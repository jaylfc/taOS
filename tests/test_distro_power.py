    assert cpu_file(env, 0, "energy_performance_preference").read_text() == "performance\n"
    assert cpu_file(env, 1, "energy_performance_preference").read_text() == "balance_performance\n"
    assert cpu_file(env, 1, "scaling_governor").read_text() == "schedutil\n"
    assert cpu_file(env, 2, "scaling_governor").read_text() == "performance\n"
    assert cpu_file(env, 0, "scaling_governor").read_text() == "schedutil\n"  # EPP cpu: governor untouched
    assert cpu_file(env, 3, "scaling_governor").read_text() == "schedutil\n"
    assert run(env, "hold-value").stdout.strip() == "100"
